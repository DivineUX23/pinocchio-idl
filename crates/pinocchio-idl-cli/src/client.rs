use anyhow::{Context, Result};
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command as ProcessCommand;

use pinocchio_idl_core::render;

use crate::{build_idl, read_metadata};

pub struct ClientOptions {
    pub manifest_path: PathBuf,
    pub out_dir: PathBuf,
    pub src_dir: Option<PathBuf>,
    pub package_name: Option<String>,
    pub run: bool,
    pub script_only: bool,
}

pub fn run_client(options: ClientOptions) -> Result<PathBuf> {
    let (metadata, lib_path) = read_metadata(&options.manifest_path).with_context(|| {
        format!(
            "Failed to read metadata {}",
            options.manifest_path.display()
        )
    })?;

    let src_dir = options.src_dir.unwrap_or_else(|| {
        if let Some(p) = lib_path {
            options
                .manifest_path
                .parent()
                .unwrap_or(Path::new("."))
                .join(p)
                .parent()
                .unwrap_or(Path::new("."))
                .to_path_buf()
        } else {
            options
                .manifest_path
                .parent()
                .unwrap_or(Path::new("."))
                .join("src")
        }
    });

    println!(
        "\x1b[36m\x1b[1m   Parsing\x1b[0m program source in {}",
        src_dir.display()
    );

    let idl = build_idl(&src_dir, metadata.clone())
        .context("IDL generation process failed - check #[p_instruction(...)]")?;

    let codama_json =
        render::to_codama_json(&idl).context("Failed to serialize IDL to Codama rootNode JSON")?;

    let out_dir = &options.out_dir;
    let src_out = out_dir.join("src");
    fs::create_dir_all(&src_out)
        .with_context(|| format!("Failed to create client directory {}", src_out.display()))?;

    // 1. Write codama.json
    let codama_path = out_dir.join("codama.json");
    fs::write(&codama_path, &codama_json)
        .with_context(|| format!("Failed to write {}", codama_path.display()))?;

    // 2. Write codama.mjs generator script
    let codama_script = r#"import { createFromRoot } from 'codama';
import { renderVisitor as renderJavaScript } from '@codama/renderers-js';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const idlPath = path.join(__dirname, 'codama.json');

const rootNode = JSON.parse(fs.readFileSync(idlPath, 'utf8'));
const codama = createFromRoot(rootNode);

await codama.accept(renderJavaScript(__dirname));
"#;
    let script_path = out_dir.join("codama.mjs");
    fs::write(&script_path, codama_script)
        .with_context(|| format!("Failed to write {}", script_path.display()))?;

    // 3. Write package.json
    let pkg_name = options
        .package_name
        .unwrap_or_else(|| format!("{}-client", metadata.name.replace('_', "-")));

    let package_json = format!(
        r#"{{
  "name": "{name}",
  "version": "{version}",
  "description": "TypeScript SDK generated by Pinocchio-IDL and Codama",
  "type": "module",
  "main": "src/generated/index.ts",
  "types": "src/generated/index.ts",
  "scripts": {{
    "generate": "node codama.mjs",
    "build": "tsc"
  }},
  "dependencies": {{
    "@solana/kit": "^8.5.0",
    "@solana/program-client-core": "^8.5.0"
  }},
  "devDependencies": {{
    "@codama/renderers-js": "^2.8.0",
    "@types/node": "^22.0.0",
    "codama": "^1.11.0",
    "typescript": "^5.0.0"
  }}
}}
"#,
        name = pkg_name,
        version = metadata.version
    );
    let pkg_path = out_dir.join("package.json");
    fs::write(&pkg_path, package_json)
        .with_context(|| format!("Failed to write {}", pkg_path.display()))?;

    // 4. Write tsconfig.json
    let tsconfig_json = r#"{
  "compilerOptions": {
    "target": "ES2022",
    "module": "ESNext",
    "moduleResolution": "bundler",
    "strict": true,
    "noImplicitAny": false,
    "esModuleInterop": true,
    "declaration": true,
    "skipLibCheck": true
  },
  "include": ["src/**/*"]
}
"#;
    let tsconfig_path = out_dir.join("tsconfig.json");
    fs::write(&tsconfig_path, tsconfig_json)
        .with_context(|| format!("Failed to write {}", tsconfig_path.display()))?;

    println!(
        "\x1b[32m\x1b[1m  Scaffolded\x1b[0m Codama client runner at {}",
        out_dir.display()
    );

    // 5. Run execution if requested and not script_only
    let should_run = options.run && !options.script_only;
    if should_run {
        println!("\x1b[34m\x1b[1m  Generating\x1b[0m TypeScript client SDK via Codama...");

        let runner_result = execute_codama_generation(out_dir);
        match runner_result {
            Ok(_) => {
                println!(
                    "\x1b[32m\x1b[1m    Finished\x1b[0m TypeScript SDK generation [{}/src/generated]",
                    out_dir.display()
                );
            }
            Err(e) => {
                println!(
                    "\x1b[33m\x1b[1m     Notice:\x1b[0m Automatic JS generation skipped ({})",
                    e
                );
                println!(
                    "\x1b[36m\x1b[1m  Next steps\x1b[0m Run the following commands to generate the client SDK:"
                );
                println!(
                    "    cd {} && npm install && node codama.mjs",
                    out_dir.display()
                );
            }
        }
    } else {
        println!(
            "\x1b[36m\x1b[1m  Next steps\x1b[0m Run the following commands to generate the client SDK:"
        );
        println!(
            "    cd {} && npm install && node codama.mjs",
            out_dir.display()
        );
    }

    Ok(out_dir.clone())
}

fn execute_codama_generation(out_dir: &Path) -> Result<()> {
    // Check if node_modules exists, otherwise install dependencies
    let has_node_modules = out_dir.join("node_modules").exists();

    if !has_node_modules {
        // Try bun first, then npm, then yarn
        let installed = if has_command("npm") {
            let status = ProcessCommand::new("npm")
                .arg("install")
                .current_dir(out_dir)
                .status()
                .context("Failed to run npm install")?;
            status.success()
        } else if has_command("bun") {
            let status = ProcessCommand::new("bun")
                .arg("install")
                .current_dir(out_dir)
                .status()
                .context("Failed to run bun install")?;
            status.success()
        } else if has_command("yarn") {
            let status = ProcessCommand::new("yarn")
                .arg("install")
                .current_dir(out_dir)
                .status()
                .context("Failed to run yarn install")?;
            status.success()
        } else {
            anyhow::bail!("No JS package manager (npm, bun, or yarn) found in PATH");
        };

        if !installed {
            anyhow::bail!("Dependency installation failed");
        }
    }

    // Now run node codama.mjs (or bun codama.mjs)
    if has_command("node") {
        let status = ProcessCommand::new("node")
            .arg("codama.mjs")
            .current_dir(out_dir)
            .status()
            .context("Failed to execute node codama.mjs")?;

        if !status.success() {
            anyhow::bail!("`node codama.mjs` exited with error");
        }
    } else if has_command("bun") {
        let status = ProcessCommand::new("bun")
            .arg("codama.mjs")
            .current_dir(out_dir)
            .status()
            .context("Failed to execute bun codama.mjs")?;

        if !status.success() {
            anyhow::bail!("`bun codama.mjs` exited with error");
        }
    } else {
        anyhow::bail!("No Node.js or Bun runtime found in PATH");
    }

    Ok(())
}

fn has_command(cmd: &str) -> bool {
    ProcessCommand::new("which")
        .arg(cmd)
        .output()
        .map(|o| o.status.success())
        .unwrap_or(false)
}
